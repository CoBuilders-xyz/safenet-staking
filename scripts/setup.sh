#!/usr/bin/env bash
# Prepares this worktree. Safe to run again.
#
#   pnpm bootstrap                                     everything
#   pnpm --filter @cobuilders/safenet-core bootstrap   one package
set -euo pipefail
cd "$(dirname "$0")/.."
ROOT="$PWD"
say() { printf "  %-34s %s\n" "$1" "$2"; }

echo
echo "  Safenet stack setup"
echo

# --- 1. required tools -------------------------------------------------------
missing=0
need() {
  if command -v "$1" >/dev/null 2>&1; then
    say "$1" "$(eval "$2" 2>/dev/null | head -1)"
  else
    say "$1" "MISSING — $3"
    missing=1
  fi
}
need node   "node -v"          "install Node 22, see .nvmrc"
need pnpm   "pnpm -v"          "npm i -g pnpm"
need anvil  "anvil --version"  "curl -L https://foundry.paradigm.xyz | bash && foundryup"
need cast   "cast --version"   "comes with foundry"
need docker "docker --version" "Docker Desktop, only needed for subgraph work"
need gh     "gh --version"     "brew install gh"
echo

if [ "$missing" -eq 1 ]; then
  echo "  Install what is missing above, then run this again."
  echo
  exit 1
fi

# --- 2. per-worktree ports ---------------------------------------------------
# Several worktrees run at once, so ports must not collide.
WT="$(basename "$ROOT")"
OFFSET=$(( $(printf '%s' "$WT" | cksum | cut -d' ' -f1) % 40 * 10 ))
cat > .env.ports <<PORTS
# Generated by scripts/setup.sh for worktree: $WT. Do not commit.
COMPOSE_PROJECT_NAME=safenet-$WT
WEB_PORT=$((5173 + OFFSET))
E2E_PORT=$((5273 + OFFSET))
ANVIL_PORT=$((8545 + OFFSET))
GRAPH_NODE_PORT=$((8000 + OFFSET))
GRAPH_WS_PORT=$((8100 + OFFSET))
GRAPH_ADMIN_PORT=$((8020 + OFFSET))
GRAPH_STATUS_PORT=$((8030 + OFFSET))
POSTGRES_PORT=$((5432 + OFFSET))
IPFS_PORT=$((5001 + OFFSET))
PORTS
say "worktree" "$WT"
say "port offset" "+$OFFSET, see .env.ports"

# --- 3. dependencies ---------------------------------------------------------
pnpm install --silent
say "dependencies" "installed"

# --- 4. per-package bootstrap ------------------------------------------------
pnpm -r --if-present run bootstrap >/dev/null
say "package bootstrap" "done"

# --- 5. browser for the end-to-end tests -------------------------------------
# Playwright skips the download when this Chromium build is already installed.
if ! out="$(pnpm --filter @cobuilders/safenet-web exec playwright install chromium 2>&1)"; then
  printf '%s\n' "$out" | tail -5
  exit 1
fi
say "playwright chromium" "installed"

# --- 6. secrets --------------------------------------------------------------
# Secrets live in the Vercel project. They come down into .env.local, which stays on
# the host, git-ignored, and passed into a container only at exec time.
pulled=0
if command -v vercel >/dev/null 2>&1 && vercel whoami >/dev/null 2>&1; then
  echo
  if pnpm --silent run link:services && pnpm --silent run env:pull; then
    pulled=1
  fi
  echo
  if [ "$pulled" -eq 1 ]; then
    say ".env.local" "pulled from Vercel"
  else
    say "vercel" "link or pull failed, see above"
  fi
else
  say "vercel" "not signed in, secrets not pulled"
  echo "    After 'vercel login', run:"
  echo "      pnpm link:services"
  echo "      pnpm env:pull"
fi

if [ "$pulled" -eq 0 ] && [ ! -f .env.local ]; then
  cat > .env.local <<'ENVV'
# Host-only. Never committed, never baked into an image.
# Normally written by `pnpm env:pull`. Fill it by hand only without Vercel access.
# Archive RPC endpoints for fork tests and deep ABI verification. Public fallbacks
# are used when these are empty.
MAINNET_RPC_URL=
GNOSIS_RPC_URL=
ENVV
  say ".env.local" "template created"
elif [ "$pulled" -eq 0 ]; then
  say ".env.local" "present"
fi

echo
echo "  Ready. Next:"
echo "    pnpm check         lint, browser safety and types"
echo "    pnpm test          unit tests"
echo "    pnpm verify:abis   prove our ABIs still match the chain"
echo "    pnpm dev           start the app"
echo
