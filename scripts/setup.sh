#!/usr/bin/env bash
# Prepares this worktree. Safe to run again (D-009).
#
#   pnpm bootstrap                      everything
#   pnpm --filter @safenet/core setup   one package
set -euo pipefail
cd "$(dirname "$0")/.."
ROOT="$PWD"
say() { printf "  %-34s %s\n" "$1" "$2"; }

echo
echo "  Safenet stack setup"
echo

# --- 1. required tools -------------------------------------------------------
missing=0
need() {
  if command -v "$1" >/dev/null 2>&1; then
    say "$1" "$(eval "$2" 2>/dev/null | head -1)"
  else
    say "$1" "MISSING — $3"
    missing=1
  fi
}
need node   "node -v"          "install Node 22, see .nvmrc"
need pnpm   "pnpm -v"          "npm i -g pnpm"
need anvil  "anvil --version"  "curl -L https://foundry.paradigm.xyz | bash && foundryup"
need cast   "cast --version"   "comes with foundry"
need docker "docker --version" "Docker Desktop, only needed for subgraph work"
need gh     "gh --version"     "brew install gh"
echo

if [ "$missing" -eq 1 ]; then
  echo "  Install what is missing above, then run this again."
  echo
  exit 1
fi

# --- 2. per-worktree ports ---------------------------------------------------
# Several worktrees run at once, so ports must not collide (D-008).
WT="$(basename "$ROOT")"
OFFSET=$(( $(printf '%s' "$WT" | cksum | cut -d' ' -f1) % 40 * 10 ))
cat > .env.ports <<PORTS
# Generated by scripts/setup.sh for worktree: $WT. Do not commit.
COMPOSE_PROJECT_NAME=safenet-$WT
WEB_PORT=$((5173 + OFFSET))
E2E_PORT=$((5273 + OFFSET))
ANVIL_PORT=$((8545 + OFFSET))
GRAPH_NODE_PORT=$((8000 + OFFSET))
POSTGRES_PORT=$((5432 + OFFSET))
IPFS_PORT=$((5001 + OFFSET))
PORTS
say "worktree" "$WT"
say "port offset" "+$OFFSET, see .env.ports"

# --- 3. secrets --------------------------------------------------------------
# Secrets stay on the host, git-ignored, passed into the container at exec time (D-039).
if [ ! -f .env.local ]; then
  cat > .env.local <<'ENVV'
# Host-only. Never committed, never baked into an image.
# Archive node for Anvil fork tests and deep ABI verification (D-033).
ALCHEMY_MAINNET_RPC_URL=
# Optional overrides. Public fallbacks are used when these are empty.
MAINNET_RPC_URL=
GNOSIS_RPC_URL=
ENVV
  say ".env.local" "created, fill in ALCHEMY_MAINNET_RPC_URL"
else
  say ".env.local" "present"
fi

# --- 4. dependencies ---------------------------------------------------------
pnpm install --silent
say "dependencies" "installed"

# --- 5. per-package setup ----------------------------------------------------
pnpm -r --if-present run setup >/dev/null 2>&1 || true
say "package setup" "done"

echo
echo "  Ready. Next:"
echo "    pnpm check         lint and types (no tests yet)"
echo "    pnpm verify:abis   prove our ABIs still match the chain"
echo "    pnpm dev           start the app"
echo
